from fpdf import FPDF
from datetime import datetime
import io

class EnergyAuditPDF(FPDF):
    def header(self):
        self.set_fill_color(16, 185, 129)  # Emerald green header bar
        self.rect(0, 0, 210, 8, 'F')
        self.set_font('Helvetica', 'B', 18)
        self.set_text_color(15, 23, 42)
        self.ln(6)
        self.cell(0, 10, 'POWER BILL COACH - ENERGY AUDIT REPORT', ln=True, align='L')
        self.set_font('Helvetica', '', 10)
        self.set_text_color(100, 116, 139)
        self.cell(0, 5, f'Generated on {datetime.now().strftime("%B %d, %Y - %I:%M %p")} | Household & Society Energy Advisory', ln=True, align='L')
        self.ln(6)
        self.line(10, self.get_y(), 200, self.get_y())
        self.ln(6)

    def footer(self):
        self.set_y(-15)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(148, 163, 184)
        self.cell(0, 10, 'Confidential | Generated by Power Bill Coach AI Engine | Page ' + str(self.page_no()), 0, 0, 'C')

def generate_pdf_audit(insights_list, forecast_data, profile_name="Sample Household"):
    """Creates a professional 1-page PDF Energy Audit and Savings Plan."""
    pdf = EnergyAuditPDF(orientation='P', unit='mm', format='A4')
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # Section 1: Executive Summary Box
    pdf.set_fill_color(241, 245, 249)
    pdf.set_draw_color(203, 213, 225)
    pdf.rect(10, pdf.get_y(), 190, 28, 'FD')
    
    start_y = pdf.get_y()
    pdf.set_xy(14, start_y + 4)
    pdf.set_font('Helvetica', 'B', 11)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(60, 6, 'CURRENT RUN-RATE', ln=False)
    pdf.cell(60, 6, 'POTENTIAL SAVINGS', ln=False)
    pdf.cell(60, 6, 'OPTIMIZED BILL', ln=True)

    pdf.set_xy(14, start_y + 11)
    pdf.set_font('Helvetica', 'B', 15)
    pdf.set_text_color(239, 68, 68)  # Red for high bill
    pdf.cell(60, 8, f"INR {forecast_data['forecast_bill_inr']:,.0f}", ln=False)
    
    pdf.set_text_color(16, 185, 129)  # Green for savings
    pdf.cell(60, 8, f"INR {forecast_data['achievable_savings_inr']:,.0f} / mo", ln=False)
    
    pdf.set_text_color(14, 165, 233)  # Blue for optimized
    pdf.cell(60, 8, f"INR {forecast_data['optimized_bill_inr']:,.0f}", ln=True)
    
    pdf.set_xy(10, start_y + 34)

    # Section 2: Three Plain-English Insights
    pdf.set_font('Helvetica', 'B', 13)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 8, 'TOP THREE ENERGY INSIGHTS & WASTE AUDIT', ln=True)
    pdf.ln(2)

    for idx, insight in enumerate(insights_list, 1):
        pdf.set_font('Helvetica', 'B', 11)
        pdf.set_text_color(30, 41, 59)
        pdf.cell(0, 6, f"{idx}. {insight['title']} ({insight['metric_label']}: {insight['metric_value']})", ln=True)

        pdf.set_font('Helvetica', '', 9.5)
        pdf.set_text_color(71, 85, 105)
        # Clean markdown bold asterisks for clean PDF rendering
        clean_exp = insight['explanation'].replace('**', '').replace('🔴', '').replace('🟢', '').replace('🟠', '').replace('⚠️', '')
        pdf.multi_cell(190, 5, clean_exp)
        
        pdf.set_font('Helvetica', 'I', 9)
        pdf.set_text_color(5, 150, 105)
        clean_action = insight['action_plan'].replace('**', '').replace('💡', '').replace('🎯', '')
        pdf.multi_cell(190, 4.5, f"Action: {clean_action[:220]}...")
        pdf.ln(4)

    # Section 3: Next Month 30-Day Forecast Table
    pdf.ln(2)
    pdf.set_font('Helvetica', 'B', 13)
    pdf.set_text_color(15, 23, 42)
    pdf.cell(0, 8, 'NEXT MONTH SLAB-WISE BILL BREAKDOWN', ln=True)
    pdf.ln(1)

    # Table Header
    pdf.set_fill_color(30, 41, 59)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font('Helvetica', 'B', 9)
    pdf.cell(75, 7, 'Tariff Slab Tier', border=1, fill=True)
    pdf.cell(35, 7, 'Units (kWh)', border=1, fill=True, align='C')
    pdf.cell(40, 7, 'Rate (INR/Unit)', border=1, fill=True, align='C')
    pdf.cell(40, 7, 'Cost (INR)', border=1, fill=True, align='R')
    pdf.ln(7)

    # Table Rows
    pdf.set_text_color(51, 65, 85)
    pdf.set_font('Helvetica', '', 9)
    for row in forecast_data['bill_breakdown']:
        pdf.cell(75, 6, row['slab'], border=1)
        pdf.cell(35, 6, str(row['units']), border=1, align='C')
        pdf.cell(40, 6, f"INR {row['rate']:.2f}", border=1, align='C')
        pdf.cell(40, 6, f"INR {row['cost']:,.2f}", border=1, align='R')
        pdf.ln(6)

    # Fixed charge row
    pdf.cell(150, 6, 'Fixed Grid & Meter Maintenance Charge', border=1)
    pdf.cell(40, 6, f"INR {forecast_data['fixed_charge']:,.2f}", border=1, align='R')
    pdf.ln(6)

    # Total row
    pdf.set_font('Helvetica', 'B', 10)
    pdf.set_fill_color(241, 245, 249)
    pdf.cell(150, 7, 'Total Projected Bill (Next Month)', border=1, fill=True)
    pdf.cell(40, 7, f"INR {forecast_data['forecast_bill_inr']:,.2f}", border=1, fill=True, align='R')
    pdf.ln(8)

    return bytes(pdf.output())
